"""
Strict Data Contracts & JSON Schema Models for AIK-VdGeneration.
Adheres to docs/API_SPEC.md, .agent/skills/video-prompt-engineering/SKILL.md,
and .agent/rules/audio-sync-rules.md.
"""

from typing import List, Literal, Optional
from pydantic import BaseModel, Field, field_validator


SlideLayout = Literal[
    "title_intro",
    "bullet_list",
    "split_card",
    "quote_highlight",
    "conclusion_cta",
]

SupportedLanguage = Literal["vi", "en"]
TTSProviderType = Literal["edge_tts", "elevenlabs", "fpt"]
WorkerStage = Literal["llm", "tts", "render"]


class SlideScriptItem(BaseModel):
    """Schema for an individual presentation slide generated by the LLM."""

    slide_index: int = Field(
        ...,
        ge=1,
        description="1-based sequential index of the slide.",
    )
    layout: SlideLayout = Field(
        ...,
        description="Visual layout template identifier for Remotion composition.",
    )
    heading: str = Field(
        ...,
        min_length=1,
        description="Catchy, concise slide title (under 8 words).",
    )
    bullet_points: List[str] = Field(
        default_factory=list,
        description="2 to 4 concise bullet points (each under 12 words, max 5 items).",
    )
    voiceover_script: str = Field(
        ...,
        min_length=1,
        description="Natural, spoken narrative script for TTS voiceover (2 to 4 sentences).",
    )
    visual_keywords: str = Field(
        ...,
        min_length=1,
        description="3 to 5 English keywords for background stock imagery search.",
    )

    @field_validator("heading", "voiceover_script", "visual_keywords")
    @classmethod
    def must_not_be_blank(cls, value: str) -> str:
        cleaned = value.strip()
        if not cleaned:
            raise ValueError("Field cannot be empty or whitespace only.")
        return cleaned

    @field_validator("bullet_points")
    @classmethod
    def enforce_max_bullets(cls, points: List[str]) -> List[str]:
        cleaned = [p.strip() for p in points if p and p.strip()]
        if len(cleaned) > 5:
            raise ValueError("A slide cannot exceed 5 bullet points to prevent visual overcrowding.")
        return cleaned


class PresentationScript(BaseModel):
    """Root structured output schema returned by the LLM script generator."""

    title: str = Field(
        ...,
        min_length=1,
        description="Overall presentation title.",
    )
    language: SupportedLanguage = Field(
        ...,
        description="Language code of the presentation ('vi' or 'en').",
    )
    theme: str = Field(
        default="modern_tech",
        description="Visual theme identifier (e.g. 'modern_tech', 'corporate', 'minimal').",
    )
    slides: List[SlideScriptItem] = Field(
        ...,
        min_length=3,
        max_length=8,
        description="Ordered sequence of 3 to 8 presentation slides.",
    )


class StyleSettings(BaseModel):
    theme: str = Field(default="modern_tech", description="Visual theme identifier")
    color_palette: str = Field(default="indigo_slate", description="Color palette preset")
    font_pair: str = Field(default="Inter_Roboto", description="Typography pairing")


class VoiceSettings(BaseModel):
    provider: TTSProviderType = Field(
        default="edge_tts",
        description="TTS synthesis provider ('edge_tts', 'elevenlabs', or 'fpt')",
    )
    voice_id: Optional[str] = Field(
        default=None,
        description="Specific voice identifier (defaults based on language if omitted)",
    )
    speed: float = Field(default=1.0, ge=0.5, le=2.0, description="Speech rate multiplier")


class RemotionThemeProps(BaseModel):
    """Visual theme properties passed into Remotion composition."""

    backgroundColor: str = Field(default="#0f172a")
    primaryColor: str = Field(default="#38bdf8")
    textColor: str = Field(default="#f8fafc")
    fontFamily: str = Field(default="Inter, sans-serif")


class RemotionBGMProps(BaseModel):
    """Background music configuration for Remotion composition."""

    enabled: bool = Field(default=False)
    audio_url: Optional[str] = Field(default=None)
    volume: float = Field(default=0.15, ge=0.0, le=1.0)


class RemotionSlideProps(BaseModel):
    """Synchronized slide data with synthesized audio metadata for Remotion (M1.3)."""

    slide_index: int = Field(..., ge=1)
    layout: SlideLayout
    heading: str
    bullet_points: List[str] = Field(default_factory=list)
    voiceover_script: str
    voiceover_audio_url: str = Field(..., description="Relative URL or path to the MP3 asset")
    voiceover_audio_path: str = Field(..., description="Absolute local path to the MP3 asset")
    voiceover_duration_seconds: float = Field(..., gt=0, description="Exact audio duration in seconds")
    calculated_frames: int = Field(..., ge=90, description="Calculated frame count at target FPS")
    background_image_url: Optional[str] = Field(default=None)


class RemotionCompositionProps(BaseModel):
    """Complete Remotion input props contract matching docs/API_SPEC.md Section 3."""

    project_title: str
    fps: int = Field(default=30, ge=24, le=60)
    width: int = Field(default=1920)
    height: int = Field(default=1080)
    total_duration_seconds: float = Field(..., gt=0)
    total_frames: int = Field(..., ge=90)
    theme: RemotionThemeProps = Field(default_factory=RemotionThemeProps)
    slides: List[RemotionSlideProps]
    bgm: RemotionBGMProps = Field(default_factory=RemotionBGMProps)


class ScriptGenerateRequest(BaseModel):
    """Request payload for standalone LLM script generation (Milestone M1.2)."""

    prompt: str = Field(
        ...,
        min_length=3,
        description="User topic, prompt, or raw text to convert into a slide script.",
    )
    language: SupportedLanguage = Field(
        default="vi",
        description="Target script language: 'vi' for Vietnamese, 'en' for English.",
    )
    target_duration_seconds: int = Field(
        default=60,
        ge=15,
        le=600,
        description="Approximate target video duration in seconds.",
    )
    theme: str = Field(
        default="modern_tech",
        description="Visual theme hint for the script.",
    )
    model: Optional[str] = Field(
        default=None,
        description="Optional override for the Gemini model ID (e.g., 'gemini-3.8-flash').",
    )


class AudioSynthesizeRequest(BaseModel):
    """Request payload for standalone M1.3 TTS audio synthesis & frame calculation."""

    script: PresentationScript
    voice_settings: VoiceSettings = Field(default_factory=VoiceSettings)
    aspect_ratio: Literal["16:9", "9:16"] = Field(default="16:9")
    fps: int = Field(default=30, ge=24, le=60)
    job_id: Optional[str] = Field(default=None)


class VideoGenerateRequest(BaseModel):
    """Request payload for full prompt-to-video generation pipeline."""

    prompt: str = Field(
        ...,
        min_length=3,
        description="User prompt describing the video topic or raw text.",
    )
    language: SupportedLanguage = Field(
        default="vi",
        description="'vi' for Vietnamese, 'en' for English.",
    )
    aspect_ratio: Literal["16:9", "9:16"] = Field(
        default="16:9",
        description="Video aspect ratio ('16:9' widescreen or '9:16' vertical).",
    )
    target_duration_seconds: int = Field(
        default=60,
        ge=15,
        le=600,
        description="Target duration in seconds.",
    )
    style: StyleSettings = Field(default_factory=StyleSettings)
    voice_settings: VoiceSettings = Field(default_factory=VoiceSettings)
    model: Optional[str] = Field(
        default=None,
        description="Optional override for the Gemini model ID (defaults to GEMINI_MODEL).",
    )
    render_video: bool = Field(
        default=False,
        description="When True, also executes Stage 3 Remotion MP4 compilation in the background.",
    )


class VideoJobResponse(BaseModel):
    """Immediate 202 Accepted response when a video job is queued."""

    job_id: str
    status: Literal["queued", "processing", "completed", "failed"]
    estimated_time_seconds: int = 45
    websocket_url: str
    message: str


class WebSocketProgressEvent(BaseModel):
    """Realtime progress event payload matching docs/API_SPEC.md Section 4."""

    job_id: str
    step: str
    progress_percentage: int = Field(ge=0, le=100)
    message: str
    timestamp: str


class QueueTaskPayload(BaseModel):
    """Serialized task envelope pushed onto Redis / Memory stage queues."""

    job_id: str
    stage: WorkerStage
    request: VideoGenerateRequest
    attempt: int = Field(default=1, ge=1)
    max_retries: int = Field(default=3, ge=1)
    created_at: str


class JobStatusResponse(BaseModel):
    """Detailed status and artifact payload for an active or completed job."""

    job_id: str
    status: Literal[
        "queued",
        "generating_script",
        "script_ready",
        "synthesizing_audio",
        "audio_ready",
        "rendering_video",
        "completed",
        "failed",
    ]
    progress_percentage: int = Field(ge=0, le=100)
    current_stage: Optional[WorkerStage] = None
    render_requested: bool = False
    retry_count: int = Field(default=0, ge=0)
    model_used: Optional[str] = None
    voice_provider_used: Optional[str] = None
    script: Optional[PresentationScript] = None
    remotion_props: Optional[RemotionCompositionProps] = None
    output_video_path: Optional[str] = None
    progress_events: List[WebSocketProgressEvent] = Field(default_factory=list)
    error: Optional[str] = None


class QueueStatsResponse(BaseModel):
    """Operational telemetry for the asynchronous queue backend."""

    backend: Literal["redis", "memory"]
    redis_connected: bool
    queues: dict[str, int]
    dead_letter_count: int = 0
    total_jobs: int = 0
